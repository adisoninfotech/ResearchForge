class Dataset(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    __tablename__ = "datasets"

    project_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("projects.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    created_by_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    provenance_type: Mapped[DatasetProvenanceType] = mapped_column(
        Enum(
            DatasetProvenanceType,
            name="dataset_provenance_type",
            values_callable=lambda e: [i.value for i in e],
        ),
        nullable=False,
    )
    synthetic: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    source_description: Mapped[str | None] = mapped_column(Text, nullable=True)
    license: Mapped[str | None] = mapped_column(String(255), nullable=True)
    provenance_label: Mapped[str] = mapped_column(Text, nullable=False)
    label_locked: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    current_version_id: Mapped[uuid.UUID | None] = mapped_column(Uuid(as_uuid=True), nullable=True)
    creation_parameters: Mapped[dict[str, Any] | None] = mapped_column(
        JSON().with_variant(JSONB(), "postgresql"),
        nullable=True,
    )
    random_seed: Mapped[int | None] = mapped_column(Integer, nullable=True)

    project: Mapped[Project] = relationship()
    created_by: Mapped[User | None] = relationship()
    versions: Mapped[list[DatasetVersion]] = relationship(
        back_populates="dataset",
        cascade="all, delete-orphan",
        order_by="DatasetVersion.version_number",
    )


class DatasetVersion(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    __tablename__ = "dataset_versions"
    __table_args__ = (UniqueConstraint("dataset_id", "version_number", name="uq_dataset_version"),)

    dataset_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("datasets.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    project_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("projects.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    version_number: Mapped[int] = mapped_column(Integer, nullable=False)
    storage_key: Mapped[str] = mapped_column(String(1024), nullable=False, unique=True)
    original_storage_key: Mapped[str | None] = mapped_column(String(1024), nullable=True)
    content_sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    row_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    column_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    schema_json: Mapped[dict[str, Any]] = mapped_column(
        JSON().with_variant(JSONB(), "postgresql"),
        nullable=False,
        default=dict,
    )
    is_immutable_original: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    dataset: Mapped[Dataset] = relationship(back_populates="versions")
    columns: Mapped[list[DatasetColumn]] = relationship(
        back_populates="version",
        cascade="all, delete-orphan",
        order_by="DatasetColumn.position",
    )
    profile: Mapped[DatasetProfile | None] = relationship(
        back_populates="version",
        uselist=False,
        cascade="all, delete-orphan",
    )


class DatasetColumn(Base, UUIDPrimaryKeyMixin):
    __tablename__ = "dataset_columns"
    __table_args__ = (UniqueConstraint("version_id", "name", name="uq_dataset_column_name"),)

    version_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("dataset_versions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    position: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    inferred_type: Mapped[DatasetColumnType] = mapped_column(
        Enum(
            DatasetColumnType,
            name="dataset_column_type",
            values_callable=lambda e: [i.value for i in e],
        ),
        nullable=False,
    )
    override_type: Mapped[DatasetColumnType | None] = mapped_column(
        Enum(
            DatasetColumnType,
            name="dataset_column_override_type",
            values_callable=lambda e: [i.value for i in e],
        ),
        nullable=True,
    )
    nullable_ratio: Mapped[float] = mapped_column(Float, nullable=False, default=0.0)
    unique_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    stats_json: Mapped[dict[str, Any] | None] = mapped_column(
        JSON().with_variant(JSONB(), "postgresql"),
        nullable=True,
    )

    version: Mapped[DatasetVersion] = relationship(back_populates="columns")

    @property
    def effective_type(self) -> DatasetColumnType:
        return self.override_type or self.inferred_type


