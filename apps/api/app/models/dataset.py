class ManuscriptAssetRef(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Cross-reference of figures/tables inserted into manuscript sections."""

    __tablename__ = "manuscript_asset_refs"
    __table_args__ = (
        UniqueConstraint(
            "project_id",
            "asset_type",
            "asset_stable_id",
            "section_id",
            name="uq_manuscript_asset_ref",
        ),
    )

    project_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("projects.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    section_id: Mapped[uuid.UUID] = mapped_column(Uuid(as_uuid=True), nullable=False, index=True)
    asset_type: Mapped[str] = mapped_column(String(16), nullable=False)  # figure | table
    asset_stable_id: Mapped[str] = mapped_column(String(64), nullable=False)
    cross_ref: Mapped[str] = mapped_column(String(64), nullable=False)
    caption: Mapped[str] = mapped_column(Text, nullable=False, default="")
    source: Mapped[str] = mapped_column(Text, nullable=False, default="")
    provenance: Mapped[str] = mapped_column(Text, nullable=False, default="")
    alt_text: Mapped[str] = mapped_column(Text, nullable=False, default="")
